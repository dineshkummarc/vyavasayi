#!/usr/bin/env php
<?php
/**
 * Rebuilds public/js/icons.js from the SVG files in public/icons/{ui,social}.
 *
 *   php bin/build-icons.php
 *
 * Run it whenever you add, change or remove an icon file. PHP views read the .svg files directly,
 * so only the JavaScript copy needs rebuilding.
 */
define('BASE_PATH', dirname(__DIR__));
require_once BASE_PATH . '/app/Helpers/Icon.php';

use App\Helpers\Icon;

$map = [];
foreach (Icon::names() as $name) {
    $map[$name] = Icon::svg($name);
}

$json = json_encode($map, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE);
// the class attribute is rewritten at runtime, keep a stable marker for it
$js = <<<JS
/* AUTO-GENERATED by bin/build-icons.php from public/icons — do not edit by hand. */
(function (w) {
    var MAP = $json;
    function esc(s) { return String(s).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;'); }
    w.Icons = {
        names: function () { return Object.keys(MAP); },
        has: function (name) { return Object.prototype.hasOwnProperty.call(MAP, name); },
        /** Returns an inline <svg> string. Icons use 1em size and currentColor, like text. */
        svg: function (name, cls, style) {
            var s = MAP[name] || MAP.circle;
            if (!MAP[name]) name = 'circle';
            if (cls)   s = s.replace('class="ic ic-' + name + '"', 'class="ic ic-' + name + ' ' + esc(cls) + '"');
            if (style) s = s.replace('<svg ', '<svg style="' + esc(style) + '" ');
            return s;
        },
        /** Replace the contents of an element (e.g. a button) with an icon. */
        set: function (el, name, cls, style) { if (el) el.innerHTML = w.Icons.svg(name, cls, style); }
    };
})(window);

JS;
file_put_contents(BASE_PATH . '/public/js/icons.js', $js);
echo 'Wrote public/js/icons.js (' . count($map) . ' icons, ' . round(strlen($js) / 1024, 1) . " KB)\n";
